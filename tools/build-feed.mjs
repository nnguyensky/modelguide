// Build feed.xml (RSS 2.0) from the timeline in data.js.
// Usage:  node tools/build-feed.mjs          → writes feed.xml
//         node tools/build-feed.mjs --check  → exits 1 if feed.xml is out of date (used in CI)
import { readFileSync, writeFileSync, existsSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
import vm from 'node:vm';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const ctx = { window: {} };
vm.runInNewContext(readFileSync(path.join(root, 'data.js'), 'utf8'), ctx);
const MG = ctx.window.MG;
const site = MG.siteUrl.replace(/\/?$/, '/');

const xml = (s) => String(s).replace(/&(?!amp;|lt;|gt;|quot;|#\d+;)/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');
const plain = (s) => String(s).replace(/<[^>]+>/g, '').replace(/&amp;/g, '&').replace(/&gt;/g, '>').replace(/&lt;/g, '<');
const strip = (s) => String(s).replace(/^[^\p{L}\p{N}$]+\s*/u, '');
const rfc822 = (iso) => new Date(iso + 'T12:00:00Z').toUTCString();
const slug = (s) => plain(strip(s)).toLowerCase().replace(/[^a-z0-9]+/g, '-').replace(/^-|-$/g, '');

const items = [...MG.timeline]
  .sort((a, b) => (b.added + b.iso).localeCompare(a.added + a.iso))
  .map((t) => `    <item>
      <title>${xml(plain(strip(t.t)))} (${xml(t.p)})</title>
      <link>${site}#changes</link>
      <guid isPermaLink="false">model-guide-${t.iso}-${slug(t.t)}</guid>
      <pubDate>${rfc822(t.added > t.iso ? t.added : t.iso)}</pubDate>
      <category>${xml(t.p)}</category>
      <description><![CDATA[<p><strong>${t.d}</strong> · ${t.p}</p><p>${t.b}</p>]]></description>
    </item>`).join('\n');

const feed = `<?xml version="1.0" encoding="UTF-8"?>
<!-- Generated by tools/build-feed.mjs from data.js — do not edit by hand. -->
<rss version="2.0" xmlns:atom="http://www.w3.org/2005/Atom">
  <channel>
    <title>Model Guide — price and model changes</title>
    <link>${site}</link>
    <atom:link href="${site}feed.xml" rel="self" type="application/rss+xml"/>
    <description>Launches, price cuts, promos and scheduled price changes for AI models (Claude, GPT, Gemini, Grok, open-weight).</description>
    <language>en</language>
    <lastBuildDate>${rfc822(MG.checked)}</lastBuildDate>
${items}
  </channel>
</rss>
`;

const out = path.join(root, 'feed.xml');
if (process.argv.includes('--check')) {
  const cur = existsSync(out) ? readFileSync(out, 'utf8') : '';
  if (cur !== feed) { console.error('feed.xml is out of date — run: node tools/build-feed.mjs'); process.exit(1); }
  console.log('feed.xml is up to date');
} else {
  writeFileSync(out, feed);
  console.log(`feed.xml written (${MG.timeline.length} items)`);
}
